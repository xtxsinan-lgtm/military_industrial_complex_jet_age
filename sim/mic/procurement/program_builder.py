def write_all_program_files(output_dir: Optional[Path] = None) -> List[Path]:
    """Write all 16 historical program JSONs + threats + budget index to sim/data/programs/."""
    target = output_dir if output_dir is not None else DEFAULT_PROGRAMS_DIR
    target.mkdir(parents=True, exist_ok=True)
    written: List[Path] = []

    for prog in build_all_program_dicts():
        path = target / f"{prog['id']}.json"
        with open(path, "w", encoding="utf-8") as f:
            json.dump(prog, f, indent=2)
            f.write("\n")
        written.append(path)

    threats_path = target / "threats_1945_1960.json"
    with open(threats_path, "w", encoding="utf-8") as f:
        json.dump(build_threats_dict(), f, indent=2)
        f.write("\n")
    written.append(threats_path)

    budget_path = target / "budget_index_1945_1960.json"
    with open(budget_path, "w", encoding="utf-8") as f:
        json.dump(build_budget_index_dict(), f, indent=2)
        f.write("\n")
    written.append(budget_path)

    return written


